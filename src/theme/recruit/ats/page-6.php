          <div class="aimats-faq-list">
            <details open>
              <summary><span>Q</span>AIMATSはどのような製品ですか？</summary>
              <div class="aimats-faq-answer"><span>A</span><p>AIMATSは、SES企業向けに案件・人材情報の整理、検索、AIマッチング、提案判断、営業進捗の管理を支援する業務プラットフォームです。旧来のATS機能だけではなく、案件と人材をつなぐ営業業務を中心に設計しています。</p></div>
            </details>
            <details>
              <summary><span>Q</span>AIマッチングはどのように候補を選びますか？</summary>
              <div class="aimats-faq-answer"><span>A</span><p>まず、国籍・年齢・通勤・開始時期・単価など、提案可否に関わる必須条件を確認します。その上で、スキル・工程・役割などの適合度を比較し、営業担当者が確認しやすい候補として提示する考え方です。</p></div>
            </details>
            <details>
              <summary><span>Q</span>ベクトル検索だけでマッチングしていますか？</summary>
              <div class="aimats-faq-answer"><span>A</span><p>いいえ。類似度だけではSES特有の条件を十分に扱えないため、必須条件の確認、スキル等の正規化、適合度比較、ランキングを組み合わせて候補を絞り込みます。</p></div>
            </details>
            <details>
              <summary><span>Q</span>AIが自動で提案まで実行しますか？</summary>
              <div class="aimats-faq-answer"><span>A</span><p>AIは情報整理、条件確認、候補提示などを支援します。重要な提案判断、例外条件、顧客・BPとの関係性を含む判断は、人が確認・承認するHuman-in-the-loopを基本としています。</p></div>
            </details>
            <details>
              <summary><span>Q</span>使うほどAIが自動的に学習するのですか？</summary>
              <div class="aimats-faq-answer"><span>A</span><p>無制限に自動学習するという意味ではありません。提案・面談・成約・失注などの結果や営業判断を評価データとして蓄積し、ルール・ランキング・モデルの継続改善に活用します。</p></div>
            </details>
          </div>
